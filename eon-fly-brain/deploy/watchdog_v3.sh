#!/usr/bin/env bash
# Local watchdog for the EMBODY-3WAY v3 pod.
#
# Rewritten after the first attempt lost a run. Three things went wrong there and each
# has a fix here:
#   1. An unreachable host looked exactly like a healthy quiet one, because ssh errors
#      went to /dev/null and an empty reply was read as "still working". The watchdog
#      sat for 2.5 h against a pod that was already gone. Now ssh health is probed
#      explicitly and consecutive failures are counted and acted on.
#   2. Artifacts were pulled only once, at the end, so a mid-run death left nothing.
#      Now every poll pulls incrementally.
#   3. The script was edited while running, which corrupts a running bash script
#      because bash reads it incrementally. Do not edit this file while it runs.
set -uo pipefail

POD_ID=${POD_ID:?set POD_ID}
SSH_HOST=${SSH_HOST:?set SSH_HOST}
SSH_PORT=${SSH_PORT:?set SSH_PORT}
KEY=${KEY:-$HOME/.runpod/ssh/runpodctl-ssh-key}
LOCAL_RESULTS=${LOCAL_RESULTS:-/Users/puneeth/Documents/Flycraft/eon-fly-brain/results/path2}
DEADLINE_MIN=${DEADLINE_MIN:-180}
POLL_S=${POLL_S:-120}
MAX_SSH_FAILS=${MAX_SSH_FAILS:-5}

REMOTE_RESULTS=/root/eon-fly-brain/results/path2
SSH="ssh -i $KEY -p $SSH_PORT -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o ConnectTimeout=20 -o BatchMode=yes"
started=$(date +%s)
terminated=0
ssh_fails=0

log() { echo "[watchdog $(date -u +%H:%M:%S)] $*"; }

terminate_pod() {
    [ "$terminated" -eq 1 ] && return 0
    terminated=1
    log "terminating pod $POD_ID"
    # Absence from `pod list` is the only trustworthy confirmation; the remove command's
    # output format is not something to depend on.
    for attempt in 1 2 3 4 5 6; do
        runpodctl remove pod "$POD_ID" 2>&1 | sed 's/^/[remove] /'
        sleep 8
        if ! runpodctl pod list 2>/dev/null | grep -q "$POD_ID"; then
            log "pod $POD_ID confirmed gone from pod list"
            return 0
        fi
        log "terminate attempt $attempt: still listed; retrying"
        sleep 12
    done
    log "WARNING: could not confirm termination of $POD_ID -- CHECK console.runpod.io MANUALLY"
    return 1
}
trap terminate_pod EXIT INT TERM

pull() {
    rsync -az -e "$SSH" \
        --include='embody_3way_v3*' --include='RUN_EMBODY_3WAY_V3.md' --include='V3_DONE' \
        --exclude='*' \
        "root@$SSH_HOST:$REMOTE_RESULTS/" "$LOCAL_RESULTS/" >/dev/null 2>&1
    return $?
}

while true; do
    elapsed=$(( ($(date +%s) - started) / 60 ))

    if [ "$elapsed" -ge "$DEADLINE_MIN" ]; then
        log "deadline ${DEADLINE_MIN}m reached; final pull then terminate"
        pull && log "final pull ok" || log "final pull FAILED"
        break
    fi

    # Explicit health probe. Its exit status separates "host unreachable" from
    # "host fine, nothing new to say" -- the distinction the last run did not make.
    if ! $SSH "root@$SSH_HOST" true 2>/dev/null; then
        ssh_fails=$(( ssh_fails + 1 ))
        log "SSH UNREACHABLE (${ssh_fails}/${MAX_SSH_FAILS}) at ${elapsed}m"
        if [ "$ssh_fails" -ge "$MAX_SSH_FAILS" ]; then
            log "host unreachable ${MAX_SSH_FAILS} polls running; giving up and terminating"
            break
        fi
        sleep "$POLL_S"
        continue
    fi
    ssh_fails=0

    pull && pulled="pull ok" || pulled="PULL FAILED"

    status=$($SSH "root@$SSH_HOST" "cat $REMOTE_RESULTS/V3_DONE 2>/dev/null" 2>/dev/null | tr -d '[:space:]')
    if [ -n "$status" ]; then
        log "run finished with status: $status (after ${elapsed}m)"
        pull && log "final pull ok" || log "final pull FAILED"
        break
    fi

    beat=$($SSH "root@$SSH_HOST" "cat $REMOTE_RESULTS/V3_HEARTBEAT 2>/dev/null" 2>/dev/null | tr -d '[:space:]')
    tailline=$($SSH "root@$SSH_HOST" "grep -v '^\\s*$' $REMOTE_RESULTS/embody_3way_v3_run.log 2>/dev/null | tail -1" 2>/dev/null | cut -c1-140)
    log "${elapsed}m | $pulled | beat=${beat:-NONE} | $tailline"
    sleep "$POLL_S"
done

terminate_pod
log "watchdog done"
